/* Старые адреса с решёткой → чистые URL.
 *
 * Встраивается первым тегом в <head> (см. плагин в vite.config.js) и только
 * в сборку с обычным роутером. Почему именно первым, а не в main.jsx: сразу
 * за ним в <head> инициализируется Яндекс.Метрика с `url: location.href` —
 * отработай шим позже, и каждый рекламный визит записался бы со старым
 * адресом, а отчёт «страницы входа» стал бы бесполезным.
 *
 * Зачем вообще: 109 действующих объявлений Директа ведут на адреса вида
 * «/?utm_source=…#/deklaraciya». Перемодерировать их ради переезда нельзя —
 * это дни простоя. Плюс закладки людей, ссылки в уже скачанных PDF-инструкциях
 * и статьи, которые мы будем публиковать. Шим остаётся в коде навсегда.
 *
 * Отдельно про склейку параметров: она сделана строками, а НЕ через
 * URLSearchParams. Тот декодирует «+» как пробел и переэнкодит значения, а у
 * нас через query ходят ссылка-черновик ?d=<base64 до 2000 символов> и метки
 * Директа. Порча хотя бы одного символа означает потерянный черновик.
 */
(function () {
  try {
    var hash = window.location.hash;
    // Обычные якоря (#faq) не трогаем — только маршруты вида #/путь.
    if (hash.indexOf("#/") !== 0) return;

    var rest = hash.slice(1); // «/deklaraciya/anketa?a=b» или «/deklaraciya&erid=x»

    // Рекламные площадки дописывают свои параметры после решётки через «&»
    // (Telega.in: «#/deklaraciya&erid=…»). Для роутера это часть пути, поэтому
    // разделителем считаем и «?», и «&» — что встретится раньше.
    var q = rest.indexOf("?");
    var a = rest.indexOf("&");
    var cut = q < 0 ? a : a < 0 ? q : Math.min(q, a);

    var path = cut < 0 ? rest : rest.slice(0, cut);
    var tail = cut < 0 ? "" : rest.slice(cut + 1);

    if (!path || path.charAt(0) !== "/") return;

    var search = window.location.search;
    if (tail) search = search ? search + "&" + tail : "?" + tail;

    window.history.replaceState(null, "", path + search);
  } catch (e) {
    /* Сломанный шим в самом начале <head> — это белый экран на всём сайте.
       Цена ошибки должна быть «остался старый адрес», и не больше. */
  }
})();
