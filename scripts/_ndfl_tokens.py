"""Где лежат токены Директа, Метрики и Supabase.

Порядок поиска: сначала переменная окружения, потом файл /root/.ndfl-tokens.

Почему именно так. Сессия работает в облачном контейнере, и контейнер
пересоздаётся — всё, что лежит вне репозитория, при этом пропадает. Файл
с токенами так и пропал 03.10.2026: ежедневная чистка Директа встала на
три дня, отчётов за эти дни нет вовсе. Переменные окружения задаются в
настройках окружения и переживают пересоздание, поэтому они и первые.

Файл оставлен запасным вариантом: он работает на машине разработчика и
в старых сессиях, где переменных ещё нет.

Сам токен НИКОГДА не печатается — ни в логах, ни в сообщениях об ошибке.
"""
import os
import sys

TOKENS_FILE = "/root/.ndfl-tokens"


def token(name="YANDEX_OAUTH", required=True):
    v = (os.environ.get(name) or "").strip().strip("\"'")
    if v:
        return v
    try:
        with open(TOKENS_FILE) as f:
            for line in f:
                if line.startswith(name + "="):
                    v = line.split("=", 1)[1].strip().strip("\"'")
                    if v:
                        return v
    except OSError:
        pass
    if required:
        sys.exit(
            "не найден %s: ни в переменных окружения, ни в %s.\n"
            "Положите его в настройки облачного окружения (меню окружения в "
            "шапке сессии → Edit) — так он переживёт пересоздание контейнера."
            % (name, TOKENS_FILE)
        )
    return ""
