const maxBack = Math.round(LIMITS.property * RATE); // 260 000 ₽
const maxInterest = Math.round(LIMITS.interest * RATE); // 390 000 ₽

// За какие годы вернуть налог ещё можно: ст. 79 НК — три года (X+3).
const openYears = () => {
  const now = new Date().getFullYear();
  return YEARS.filter((y) => refundDeadlineYear(y) >= now).sort((a, b) => b - a);
};

