//
// Отдельная страница, хотя есть общий разбор лечения: про зубы спрашивают
// иначе и чаще («вернуть за импланты», «вычет за брекеты», «сколько вернут за
// протезирование»), и главный вопрос у них не «сколько лимит», а «попадаю ли
// я в дорогостоящее». От ответа зависит сумма: обычное лечение упирается в
// общий социальный лимит, дорогостоящее — нет.
//
// Что мы НЕ решаем за человека: код в справке ставит клиника, а не мы и не
// налоговая. Поэтому страница учит проверить справку, а не обещает «вернём
// всё» — иначе человек заплатит за декларацию, где вместо импланта стоит
// обычное лечение, и получит отказ.
