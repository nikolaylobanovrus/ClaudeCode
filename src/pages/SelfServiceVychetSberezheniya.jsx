import { LIMITS, RATE, YEARS, refundDeadlineYear } from "../lib/ndfl/refs.js";

const openYears = () => {
  const now = new Date().getFullYear();
  return YEARS.filter((y) => refundDeadlineYear(y) >= now && y >= 2024).sort((a, b) => b - a);
};

