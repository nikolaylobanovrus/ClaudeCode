// Лендинг «Стандартный вычет на детей» (/deklaraciya/vychet-na-detey).
//
// Особый случай среди наших лендингов: обычно этот вычет даёт работодатель
// сам, и декларация не нужна. Люди ищут «вычет на детей сколько», «предел
// 450 000», «почему перестали давать вычет» — и самый полезный ответ часто
// «вам ничего делать не надо». Говорим это прямо, а декларацию предлагаем
// только для случая, когда работодатель вычет НЕ применял.
//
// Суммы и предел дохода менялись (с 2025 года — вдвое больше на второго и
// третьего ребёнка, предел 450 000 ₽ вместо 350 000 ₽), поэтому берём их из
// YEAR_RULES по каждому открытому году.
import { Link } from "react-router-dom";
import DeductionLanding, { LandingBlock } from "../components/DeductionLanding.jsx";
import { selfService } from "../data/content.js";
import { fmtRub } from "../lib/format.js";
import { RATE, YEARS, yearRules, refundDeadlineYear } from "../lib/ndfl/refs.js";

const openYears = () => {
  const now = new Date().getFullYear();
  return YEARS.filter((y) => refundDeadlineYear(y) >= now).sort((a, b) => b - a);
};

const r = yearRules(YEARS[0]);
const d = r.childDed;
// Семья с двумя детьми: вычет в месяц и возврат за год, если доход весь год
// не превышал предела.
const twoKids = d.first + d.second;

const FAQ = [
  {
    q: "Работодатель уже даёт вычет. Нужно ли что-то подавать?",
    a:
      "Нет. Если вычет виден в расчётном листке и в справке о доходах, всё уже " +
      "сделано — декларация не нужна. Она нужна только тем, у кого вычет не " +
      "применялся: не написали заявление, сменили работу, работали по договору ГПХ.",
  },
  {
    q: "Почему вычет перестали давать в середине года?",
    a:
      `Доход с начала года превысил предел — ${fmtRub(r.childLimit)} (в ${YEARS[0]} ` +
      "году). С месяца превышения вычет не применяется до конца года, а с января " +
      "начинается заново.",
  },
  {
    q: "Вычет на второго ребёнка — это сколько?",
    a:
      `С ${YEARS[0]} года: ${fmtRub(d.first)} на первого, ${fmtRub(d.second)} на ` +
      `второго, ${fmtRub(d.third)} на третьего и каждого следующего, ` +
      `${fmtRub(d.disabled)} на ребёнка с инвалидностью (он суммируется с обычным). ` +
      "Это вычет из налоговой базы за каждый месяц, а не деньги на руки: " +
      "возвращается 13% от этой суммы.",
  },
  {
    q: "До какого возраста дают вычет на ребёнка?",
    a:
      "До 18 лет, а если ребёнок учится очно — до 24 лет включительно. Порядок " +
      "рождения считается по всем детям, даже если на старших вычет уже не дают: " +
      "младший всё равно будет третьим, а не первым.",
  },
  {
    q: "Можно ли получить двойной вычет?",
    a:
      "Да — единственному родителю (если второй умер или не указан в " +
      "свидетельстве), а также когда второй родитель письменно отказался от " +
      "своего вычета в вашу пользу. Развод и неуплата алиментов основанием не " +
      "являются.",
  },
  {
    q: "За прошлые годы вернуть можно?",
    a:
      "Можно, за три последних года — декларацией за каждый год отдельно. " +
      "Понадобятся свидетельства о рождении и справки о доходах за те годы; " +
      "справки есть в Личном кабинете ФНС.",
  },
];

export default function SelfServiceVychetDeti() {
  const years = openYears();

  return (
    <DeductionLanding
      path="/deklaraciya/vychet-na-detey"
      crumb="Вычет на детей"
      preselect="deti"
      h1="Стандартный налоговый вычет на детей"
      lead={
        <>
          Его обычно даёт работодатель — и тогда делать ничего не нужно. Если
          вычет не применяли, его возвращают декларацией: с {YEARS[0]} года это{" "}
          <strong>{fmtRub(d.first)}</strong> на первого ребёнка,{" "}
          <strong>{fmtRub(d.second)}</strong> на второго и{" "}
          <strong>{fmtRub(d.third)}</strong> на третьего — за каждый месяц.
        </>
      }
      seoTitle={`Налоговый вычет на детей в ${YEARS[0]} году: суммы, предел дохода ${fmtRub(r.childLimit)} | Налог-сервис`}
      seoDescription={`Стандартный вычет на детей: ${fmtRub(d.first)} на первого, ${fmtRub(d.second)} на второго, ${fmtRub(d.third)} на третьего, ${fmtRub(d.disabled)} на ребёнка с инвалидностью. Предел дохода ${fmtRub(r.childLimit)}, до какого возраста, двойной вычет и как вернуть за прошлые годы.`}
      faq={FAQ}
      faqTitle="Частые вопросы про вычет на детей"
      ctaTitle="Вернуть вычет, который не дал работодатель"
      ctaText={`Анкета посчитает вычет по месяцам и остановит его там, где доход превысил предел. Декларация — ${fmtRub(selfService.price)}.`}
    >
      <LandingBlock title="Сколько это в деньгах">
        <p>
          Вычет — это сумма, которую каждый месяц не облагают налогом. На руки
          возвращается {Math.round(RATE * 100)}% от неё.
        </p>
        <ul className="instr__steps">
          <li>
            <strong>{fmtRub(d.first)}</strong> — на первого ребёнка;
          </li>
          <li>
            <strong>{fmtRub(d.second)}</strong> — на второго;
          </li>
          <li>
            <strong>{fmtRub(d.third)}</strong> — на третьего и каждого следующего;
          </li>
          <li>
            <strong>{fmtRub(d.disabled)}</strong> — на ребёнка с инвалидностью,
            сверх обычного вычета.
          </li>
        </ul>
        <p>
          <strong>Пример.</strong> Двое детей: вычет {fmtRub(twoKids)} в месяц. Если
          доход весь год не превысил {fmtRub(r.childLimit)}, за год это{" "}
          {fmtRub(twoKids * 12)} необлагаемого дохода и{" "}
          <strong>{fmtRub(Math.round(twoKids * 12 * RATE))}</strong> к возврату.
        </p>
      </LandingBlock>

      <LandingBlock title="Предел дохода">
        <p>
          Вычет даётся, пока доход с начала года не превысил{" "}
          {fmtRub(r.childLimit)} ({YEARS[0]} год). В месяце превышения вычет
          прекращается до конца года — именно поэтому «вычет куда-то делся» ближе к
          осени.
        </p>
        <p>Предел и суммы менялись, и у каждого года они свои:</p>
        <ul className="instr__steps">
          {years.map((y) => {
            const rr = yearRules(y);
            return (
              <li key={y}>
                <strong>{y}</strong> — {fmtRub(rr.childDed.first)} /{" "}
                {fmtRub(rr.childDed.second)} / {fmtRub(rr.childDed.third)} на
                первого, второго и третьего, предел дохода {fmtRub(rr.childLimit)}
              </li>
            );
          })}
        </ul>
      </LandingBlock>

      <LandingBlock title="Когда нужна декларация">
        <p>
          В большинстве случаев — не нужна: вычет применяет работодатель по вашему
          заявлению, автоматически, каждый месяц. Декларация нужна в трёх случаях:
        </p>
        <ul className="instr__steps">
          <li>
            <strong>Заявление не писали</strong> — работодатель не обязан давать
            вычет без него, и за прошлые годы деньги можно вернуть самому.
          </li>
          <li>
            <strong>Работали не по трудовому договору</strong> — по ГПХ вычет часто
            не применяют.
          </li>
          <li>
            <strong>Вычет дали не полностью</strong> — например, при смене работы
            новый работодатель не учёл доход с прошлого места.
          </li>
        </ul>
        <p>
          Проверить просто: откройте справку о доходах за год в Личном кабинете
          ФНС — в разделе стандартных вычетов будут коды 126–129 и суммы. Пусто —
          вычет не давали.
        </p>
      </LandingBlock>

      <LandingBlock title={`Как вернуть декларацией за ${fmtRub(selfService.price)}`}>
        <ol className="instr__steps">
          <li>
            В анкете отмечаете «Есть дети» и указываете их по очерёдности — анкета
            сама посчитает вычет по месяцам и остановит его на пределе дохода.
          </li>
          <li>
            Получаете комплект: декларация 3-НДФЛ в PDF, XML для Личного кабинета
            ФНС и заявление на возврат.
          </li>
          <li>
            Отправляете по{" "}
            <Link to="/deklaraciya/instrukciya">пошаговой инструкции</Link>.
          </li>
        </ol>
        <div className="instr__cta">
          <p>
            Вычет на детей складывается с другими: если в том же году было лечение
            или обучение, они идут в одну декларацию и увеличивают возврат.
          </p>
          <Link to="/deklaraciya/anketa?s=deti" className="btn btn--green btn--lg">
            Заполнить декларацию — {fmtRub(selfService.price)}
          </Link>
        </div>
      </LandingBlock>
    </DeductionLanding>
  );
}
