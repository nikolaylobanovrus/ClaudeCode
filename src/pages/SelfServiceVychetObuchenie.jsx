import { RATE, YEARS, yearRules, refundDeadlineYear } from "../lib/ndfl/refs.js";
import { PROOF_DOCS } from "../lib/ndfl/instrukciya.js";

const openYears = () => {
  const now = new Date().getFullYear();
  return YEARS.filter((y) => refundDeadlineYear(y) >= now).sort((a, b) => b - a);
};

const rules = yearRules(YEARS[0]);
const socialNow = rules.socialGroup; // 150 000 ₽ — общий соцлимит
const childNow = rules.childEducation; // 110 000 ₽ — на каждого ребёнка
const maxSelf = Math.round(socialNow * RATE); // 19 500 ₽
const maxChild = Math.round(childNow * RATE); // 14 300 ₽

