// Запросы здесь свои: «вычет за обучение ребёнка», «вернуть за автошколу»,
// «вычет за детский сад», «за заочное обучение». Главная путаница — два
// РАЗНЫХ лимита: своё обучение входит в общий социальный лимит, а обучение
// детей имеет собственный, на каждого ребёнка. Обе цифры менялись, поэтому
// берём их из YEAR_RULES по каждому открытому году.
import { Link } from "react-router-dom";
import DeductionLanding, { LandingBlock } from "../components/DeductionLanding.jsx";
import { selfService } from "../data/content.js";
