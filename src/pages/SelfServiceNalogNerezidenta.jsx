// Ставка нерезидента (п. 3 ст. 224 НК). В refs.js её нет сознательно: движок
// декларации её нигде не применяет — он считает только резидентские
// декларации, и фальшивая «поддержка» в справочнике вводила бы в заблуждение
// не только читателя, но и следующего разработчика.
const NR_RATE = 0.3;
const DAYS = 183;
// 0,7 кадастровой — с десятичной ЗАПЯТОЙ: число берём из справочника, а
// печатаем по-русски, иначе в тексте появляется «0.7».
const COEF = SALE_CADASTRAL_COEF.toLocaleString("ru-RU");

const YEAR = YEARS[0];
const EX = { bought: 4_500_000, sold: 5_000_000 };
const exNonResident = Math.round(EX.sold * NR_RATE);
const exResident = taxOn(EX.sold - EX.bought, YEAR, "sale");

