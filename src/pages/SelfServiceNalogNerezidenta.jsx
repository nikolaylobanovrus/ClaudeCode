// Тема перенесена из Дзена, но главное здесь — честность, а не продажа. Наша
// анкета делает декларации ТОЛЬКО для резидентов: код статуса на титульном
// листе зашит единицей (CODES.status в refs.js), а все вычеты считаются по
// резидентским правилам. Нерезиденту такая декларация не подойдёт, и страница
// говорит об этом прямо — кнопка ведёт в калькулятор, который проверяет срок
// владения (это правило одинаково для всех), а не в анкету.
//
// При этом страница людям нужна: половина тех, кто ищет «налог нерезидента с
// продажи квартиры», по итогам года оказывается резидентом, а у многих
// нерезидентов налога нет вовсе — срок владения вышел, и с 2019 года
// освобождение по сроку действует и для них.
//
// Цифры резидента — тем же кодом, что и калькулятор (taxOn): с 2025 года
// продажа облагается по ступеням 13/15%, и плоские 13% в сравнении исказили бы
// как раз то, ради чего сравнение и приводится.
