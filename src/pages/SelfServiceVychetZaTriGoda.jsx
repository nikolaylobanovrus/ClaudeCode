// Лендинг «Вычет за три года сразу» (/deklaraciya/vychet-za-tri-goda).
//
// Запросы: «вычет за 3 года», «за какие годы можно вернуть налог», «успеть
// вернуть за 2023». Тема не про вид вычета, а про СРОК — и это единственная
// страница сайта, где срочность настоящая: 31 декабря право на возврат за
// самый старый открытый год исчезает навсегда (ст. 79 НК, три года).
//
// Честность здесь важнее всего: «вернуть за три года сразу» в рекламе звучит
// как одна декларация на три года, а это три разные декларации, каждая по
// форме своего года и со своими лимитами, и каждая оплачивается отдельно.
// Человек узнаёт это ДО оплаты, а не на экране документов.
//
// Своей «ситуации» в анкете у страницы нет: год выбирается на первом шаге,
// поэтому кнопка ведёт просто в анкету (ctaHref).
import { Link } from "react-router-dom";
import DeductionLanding, { LandingBlock } from "../components/DeductionLanding.jsx";
import { selfService } from "../data/content.js";
import { fmtRub } from "../lib/format.js";
import { LIMITS, RATE, YEARS, yearRules, refundDeadlineYear } from "../lib/ndfl/refs.js";

const thisYear = () => new Date().getFullYear();
const openYears = () =>
  YEARS.filter((y) => refundDeadlineYear(y) >= thisYear()).sort((a, b) => b - a);
// Год, право на возврат за который истекает 31 декабря этого года.
const burningYear = () => openYears().find((y) => refundDeadlineYear(y) === thisYear()) ?? null;

const pct = Math.round(RATE * 100);
const maxProperty = Math.round(LIMITS.property * RATE);

