// Электронное представление декларации (файл обмена НО_НДФЛ3) для загрузки
// в Личный кабинет ФНС. Кодировка — windows-1251, имя файла по маске
// NO_NDFL3_{ИФНС}_{ИФНС}_{ИНН}_{ГГГГММДД}_{GUID}.xml.
// ВНИМАНИЕ: ЛК ФНС жёстко проверяет файл по XSD актуального приказа —
// функция помечена в интерфейсе как «бета», основной документ — PDF.
import { CODES, yearRules } from "./refs.js";
import { fmtDate as dateRu } from "./model.js";

const digits = (v) => String(v ?? "").replace(/\D/g, "");
const kop = (n) => (Math.max(0, Number(n) || 0)).toFixed(2);
const rub = (n) => String(Math.max(0, Math.round(Number(n) || 0)));

// Экранирование значений атрибутов.
const esc = (s) =>
  String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

// Элемент: el("Тег", {атрибуты}, ...дети) → строка.
function el(name, attrs = {}, ...children) {
  const a = Object.entries(attrs)
    .filter(([, v]) => v !== undefined && v !== null && v !== "")
    .map(([k, v]) => ` ${k}="${esc(v)}"`)
    .join("");
  const kids = children.filter(Boolean).join("");
  return kids ? `<${name}${a}>${kids}</${name}>` : `<${name}${a}/>`;
}

// Кодировщик windows-1251: кириллица занимает непрерывный блок 0xC0–0xFF,
// отдельно Ё/ё и №. TextEncoder cp1251 не поддерживает — пишем сами.
// Итерация по code point'ам (for..of), а не по code unit'ам: эмодзи и прочие
// символы вне BMP дают ОДИН «?», а не пару мусорных байтов.
export function encodeCp1251(str) {
  const bytes = [];
  for (const ch of str) {
    const code = ch.codePointAt(0);
    if (code <= 0x7f) bytes.push(code);
    else if (code >= 0x0410 && code <= 0x044f) bytes.push(code - 0x0410 + 0xc0); // А..я
    else if (code === 0x0401) bytes.push(0xa8); // Ё
    else if (code === 0x0451) bytes.push(0xb8); // ё
    else if (code === 0x2116) bytes.push(0xb9); // №
    else if (code === 0x00ab) bytes.push(0xab); // «
    else if (code === 0x00bb) bytes.push(0xbb); // »
    else if (code === 0x2013 || code === 0x2014) bytes.push(0x2d); // тире → дефис
    else bytes.push(0x3f); // прочее → "?"
  }
  return Uint8Array.from(bytes);
}

const isoToday = () => new Date().toISOString().slice(0, 10);

// Структура файла НО_НДФЛ3 сверена с официальными XSD-схемами ФНС
// (docs/fns-schemas/, версии 5.17–5.20) через npm run validate:xml.
export function buildDeclarationXml(model) {
  const { person, calc, year } = model;
  const rules = yearRules(year);
  const guid = crypto.randomUUID().toUpperCase();
  const stamp = isoToday().replace(/-/g, "");
  const fileId = `NO_NDFL3_${person.ifns}_${person.ifns}_${person.inn}_${stamp}_${guid}`;

  const social = model.social;
  const ap = calc.applied;
  const ct = model.contracts || {}; // реквизиты договоров для «Расчёта к Приложению 5»
  const std = calc.standard || { ordinary: 0, disabled: 0, byAgent: 0, excess: 0, declared: 0, double: false };
  const sp = calc.socialProvided || { byAgent: 0, simplified: 0 };
  const sv = calc.savings || { pds: 0, npo: 0, iis3: 0, life10: 0, byAgent: 0, simplified: 0, declared: 0, eligible: 0 };
  const pr = model.property;
  const sale = model.sale; // продажа имущества (налог к уплате, Приложение 6)
  // Возвратная сторона есть у обычной декларации и у комбинированной. У чистой
  // продажи её нет: ни зарплаты, ни вычетов, ни заявления о возврате.
  const refundSide = model.mode !== "sale";
  // Комбинированная декларация за старые годы: та же граница, что и в печати
  // (см. blankLegacy.js). В формах 2023–2024 зарплата и доход от продажи —
  // одна налоговая база, вычеты надо делить между ними; выгрузить половину
  // и назвать её декларацией нельзя.
  if (sale && model.mode === "mixed" && Number(year) < 2025)
    throw new Error(
      `Декларация за ${year} год не может совмещать продажу и вычет: ` +
        `в форме этого года обе суммы попадают в одну налоговую базу. ` +
        `Выберите 2025 год или подайте две отдельные декларации.`
    );
  // Строки формы: суммы налога — целые рубли (xs:integer), суммы дохода и
  // вычетов — рубли с копейками (xs:decimal 15.2).
  const kop2 = (n) => kop(n);
  const grp219 = ap.socialGroup; // лечение обычное + своё обучение + страхование (лимит года)
  // Строка 200 = строка 080 + строка 190 (Порядок заполнения, п. 80): к
  // социальным вычетам, заявляемым по декларации, прибавляется стандартный,
  // тоже заявляемый по декларации (то есть за вычетом данного работодателем).
  const socialTotalApplied =
    ap.socialGroup +
    ap.childEducation +
    ap.expensiveMedical -
    Math.min(ap.socialGroup + ap.childEducation + ap.expensiveMedical,
             (calc.socialProvided?.byAgent || 0) + (calc.socialProvided?.simplified || 0)) +
    (calc.standard?.declared || 0);

  // Форма менялась по годам — три семейства схем (сверено с XSD ФНС):
  const isOld = year <= 2023; // 2022–2023: идентификация через СведФЛ1, Прил7 без ДатаРегОб
  const is2025 = year >= 2025; // 2025: ГрупДоход вместо ВидДоход, урезанные наборы полей, счёт без ВидСч

  // Блок идентификации налогоплательщика внутри НПФЛ3 (после ФИОФЛ).
  const identity = isOld
    ? el(
        "СведФЛ1",
        // В СведФЛ1 ИНН, дата рождения и гражданство — атрибуты; паспорт — вложенный УдЛичн.
        { ИННФЛ: person.inn, ДатаРожд: dateRu(person.birthDate), ОКСМ: CODES.country },
        el("УдЛичн", {
          КодВидДок: person.passport.code,
          СерНомДок: `${person.passport.series} ${person.passport.number}`,
        })
      )
    : el("ИННФЛ", {}, person.inn);

  const xml =
    `<?xml version="1.0" encoding="windows-1251"?>` +
    el(
      "Файл",
      { ИдФайл: fileId, ВерсПрог: "Nalog-Service 1.0", ВерсФорм: rules.xmlVersion },
      el(
        "Документ",
        {
          КНД: "1151020",
          ДатаДок: dateRu(isoToday()),
          Период: CODES.period,
          ОтчетГод: String(year),
          КодНО: person.ifns,
          // 0 — первичная, 1+ — уточнённая. Строго строкой: el() отбрасывает
          // пустые значения, а атрибут по XSD обязателен.
          НомКорр: String(Number(model.correction) || 0),
        },
        // Сведения о налогоплательщике
        el(
          "СвНП",
          {},
          el(
            "НПФЛ3",
            { ДокПредст: CODES.taxpayerCategory, Статус: CODES.status, Тлф: person.phone || undefined },
            el("ФИОФЛ", {
              Фамилия: person.lastName,
              Имя: person.firstName,
              Отчество: person.middleName || undefined,
            }),
            identity
          )
        ),
        el("Подписант", { ПрПодп: "1" }),
        el(
          "НДФЛ3",
          {},
          // --- Раздел 1: суммы налога к уплате/возврату ---
          // Блоков может быть несколько (СумНалПуИскл227 в схеме unbounded).
          // В комбинированной декларации их два, и КБК у них РАЗНЫЕ: налог с
          // продажи человек платит сам по ст. 228, а возвращает тот, что
          // удержал работодатель. Свести их — работа налоговой на ЕНС.
          el(
            "СумНалПу",
            {},
            sale &&
              el("СумНалПуИскл227", {
                КБК: model.kbkSale,
                ОКТМО: person.oktmo,
                ПодлУпл: rub(model.owed),
                ПодлВозв: "0",
              }),
            refundSide &&
              el("СумНалПуИскл227", {
                КБК: model.kbkRefund,
                ОКТМО: person.oktmo,
                ПодлУпл: "0",
                ПодлВозв: rub(model.refund),
              })
          ),
          // Заявление о возврате (распоряжение положительным сальдо ЕНС)
          model.refund > 0 &&
            el(
              "ЗаявРаспДС",
              { Сумма: kop2(model.refund) },
              el("СвСчБанк", {
                БИК: model.bank.bik,
                // Вид счёта убран из формата с 2025 года.
                ВидСч: is2025 ? undefined : model.bank.kind,
                НомСч: model.bank.account,
              })
            ),
          // --- Раздел 2: расчёт базы и налога ---
          // Налоговых баз может быть несколько (НалБаза в схеме unbounded).
          // Зарплата и доход от продажи — РАЗНЫЕ базы, и вычеты одной к другой
          // не применяются: социальные и имущественные уменьшают зарплату,
          // вычет по продаже — доход от продажи. В комбинированной декларации
          // печатаются обе; порядок — сначала основная, потом продажа.
          refundSide &&
            el(
              "НалБаза",
              // ГрупДоход (группа доходов) с 2025 года заменил ВидДоход.
              is2025 ? { ГрупДоход: "01" } : { ВидДоход: "10" },
              el("РасчНалБаза", {
                СумДох: kop2(calc.totalIncome),
                СумДохНеНал: "0.00",
                СумДохНал: kop2(calc.totalIncome),
                СумНалВыч: kop2(calc.totalDeduction),
                СумРасх: "0.00",
                НалБаза: kop2(calc.taxBase),
                // Эти три поля есть только до 2025 года.
                "НалБаза2.1.224": is2025 ? undefined : "0.00",
                "НалБаза3.1.224": is2025 ? undefined : "0.00",
                СумИное: is2025 ? undefined : "0.00",
              }),
              el("РасчНалПУ", {
                Исчисл: rub(calc.assessed),
                Удерж: rub(calc.totalWithheld),
                СумУдержИст224: is2025 ? undefined : "0", // убрано с 2025
                СумУдержМат: "0",
                ТСУплПерЗач: "0",
                СумФиксАван: "0",
                УплИнПодлЗач: "0",
                УплПатентЗач: "0",
                ПодлУпл: "0",
                ПодлВозв: rub(model.refund),
                СумВозвУпр: "0",
              })
            ),
          sale &&
            el(
                "НалБаза",
                // 2025 — ГрупДоход «02»; до 2025 — ВидДоход «10» (основная база).
                is2025 ? { ГрупДоход: sale.groupCode } : { ВидДоход: sale.groupCode },
                el("РасчНалБаза", {
                  СумДох: kop2(sale.taxable),
                  СумДохНеНал: "0.00",
                  СумДохНал: kop2(sale.taxable),
                  СумНалВыч: kop2(sale.deduction),
                  СумРасх: "0.00",
                  НалБаза: kop2(sale.base),
                  // Поля прогрессивной базы/иного — только до 2025 (как в возврате).
                  "НалБаза2.1.224": is2025 ? undefined : "0.00",
                  "НалБаза3.1.224": is2025 ? undefined : "0.00",
                  СумИное: is2025 ? undefined : "0.00",
                }),
                el("РасчНалПУ", {
                  Исчисл: rub(sale.tax),
                  Удерж: "0",
                  СумУдержИст224: is2025 ? undefined : "0", // убрано с 2025
                  СумУдержМат: "0",
                  ТСУплПерЗач: "0",
                  СумФиксАван: "0",
                  УплИнПодлЗач: "0",
                  УплПатентЗач: "0",
                  ПодлУпл: rub(model.owed),
                  ПодлВозв: "0",
                  СумВозвУпр: "0",
                })
              ),
          // --- Приложение 1: доходы от источников в РФ ---
          // Источников может быть сколько угодно (ДоходИстРФ unbounded). У
          // возвратной стороны это работодатели, у продажи — покупатель
          // (физлицо, ИстФЛИн, код вида дохода «018» — продажа иного
          // имущества, ОКТМО по месту жительства продавца). В комбинированной
          // декларации в Приложении 1 стоят и те, и другой.
          ...(refundSide
            ? model.incomes.map((inc) =>
                el(
                  "ДоходИстРФ",
                  {
                    // Код вида дохода: 2 цифры до 2025, 3 цифры с 2025.
                    ВидДоход: is2025 ? "010" : "07",
                    // Ставка запрещена при этих кодах (Schematron ФНС) — см. ниже.
                    ОКТМО: inc.oktmo,
                    Доход: kop2(inc.income),
                    НалУдерж: rub(inc.withheld),
                  },
                  el("ИстЮЛ", { Наим: inc.name, ИННЮЛ: inc.inn, КПП: inc.kpp })
                )
              )
            : []),
          // Каждый проданный объект — свой источник дохода со своим покупателем.
          ...(sale
            ? sale.items.map((o) =>
                el(
                  "ДоходИстРФ",
                  {
                    ВидДоход: sale.incomeCode,
                    // Ставка НЕ указывается: форматный контроль ФНС (Schematron
                    // внутри XSD) требует её ТОЛЬКО при ВидДоход 25/025/046 —
                    // при других кодах файл отклоняется ЛК ФНС.
                    ОКТМО: person.oktmo,
                    Доход: kop2(o.price),
                    НалУдерж: "0",
                  },
                  // Покупатель — физлицо (типовой случай частной продажи авто):
                  // ФИО обязательно, ИНН физлица (12 цифр) — по желанию. Если
                  // введён 10-значный ИНН организации, его не пишем (для ИстЮЛ
                  // нужен КПП, который продавец не знает) — остаётся ФИО/название.
                  el("ИстФЛИн", {
                    ФИОИн: o.buyer.name || "Физическое лицо",
                    ИННФЛ: o.buyer.inn.length === 12 ? o.buyer.inn : undefined,
                  })
                )
              )
            : []),
          // --- Приложение 5: стандартные/социальные/инвестиционные вычеты ---
          model.needsApp5 &&
            el(
              "ВычСтандСоц",
              { ВычСтандСоц: kop2(socialTotalApplied) },
              // Стандартные вычеты на детей. Блок обязателен всегда: когда
              // детей не заявляли, в нём один нулевой итог.
              el("РасчВычСтанд", {
                ...(std.ordinary > 0 && !std.double ? { ВычСтРеб: kop2(std.ordinary) } : {}),
                ...(std.ordinary > 0 && std.double ? { ВычСтРебЕд: kop2(std.ordinary) } : {}),
                ...(std.disabled > 0 && !std.double ? { ВычСтРебИнв: kop2(std.disabled) } : {}),
                ...(std.disabled > 0 && std.double ? { ВычСтРебИнвЕд: kop2(std.disabled) } : {}),
                ...(std.byAgent > 0 ? { ОбщВычСтандПер: kop2(std.byAgent) } : {}),
                ...(std.excess > 0 ? { ОбщВычИзл: kop2(std.excess) } : {}),
                ОбщВычСтандДекл: kop2(std.declared),
              }),
              // Соц. вычеты без ограничения (обучение детей, дорогостоящее лечение)
              (ap.childEducation > 0 || ap.expensiveMedical > 0) &&
                el("РасчВычСоцБез219.2", {
                  СумОбуч: ap.childEducation > 0 ? kop2(ap.childEducation) : undefined,
                  СумЛечен: ap.expensiveMedical > 0 ? kop2(ap.expensiveMedical) : undefined,
                  ИтогВычСоциал: kop2(ap.childEducation + ap.expensiveMedical),
                }),
              // Соц. вычеты с ограничением (своё обучение, обычное лечение,
              // страхование, физкультурно-оздоровительные услуги)
              grp219 > 0 &&
                el("РасчВычСоц219.2", {
                  СумОбуч: calc.lines.educationSelf > 0 ? kop2(calc.lines.educationSelf) : undefined,
                  СумМедУсл: calc.lines.medicalOrdinary > 0 ? kop2(calc.lines.medicalOrdinary) : undefined,
                  // Страхование жизни по пп. 4 п. 1 ст. 219 — это строка 160
                  // (СумПенсСтрах), а не 150 (СумЛичСтрах, добровольное личное
                  // страхование). Раньше PDF печатал в 160, а XML клал в 150.
                  СумПенсСтрах: calc.lines.insurance > 0 ? kop2(calc.lines.insurance) : undefined,
                  СумФиз: calc.lines.sport > 0 ? kop2(calc.lines.sport) : undefined,
                  // 181/182 — то, что уже вернул работодатель и упрощённый
                  // порядок: строка 190 считается как (120 + 180) − (181 + 182).
                  // Без них заявка завышается и налоговая её срежет.
                  ...(sp.byAgent > 0 ? { ОбщСНВОтчПерНА: kop2(sp.byAgent) } : {}),
                  ...(sp.simplified > 0 ? { ОбщСНВУпр: kop2(sp.simplified) } : {}),
                  ОбщВычСоциал: kop2(grp219),
                }),
              // Инвестиционный вычет по взносам на ИИС (тип А)
              ap.iis > 0 &&
                el("РасчИнвВыч", {
                  СумИнвВыч219: kop2(ap.iis),
                  ИнвВычПредВосст: "0.00",
                  ИнвВычУпр: "0.00",
                }),
              // Вычет на долгосрочные сбережения (ст. 219.2), строки 235–280.
              // Нумерация подпунктов сверена с бланком Приложения 5 (лист 2):
              // 235 — пп. 1 (негосударственное пенсионное обеспечение),
              // 240 — пп. 2 (договор долгосрочных сбережений), 250 — пп. 3
              // (ИИС, открытый с 2024 года), 255 — пп. 5 (страхование жизни
              // от 10 лет). Форма 5.21, приказ ЕД-1-11/333@.
              //
              // Форма элемента зависит от года, и сильно:
              //   2022–2023 — элемента нет вовсе (вычет введён ФЗ 58-ФЗ);
              //   2024      — ровно три ОБЯЗАТЕЛЬНЫХ атрибута (пп. 2, пп. 3 и
              //               упрощённый порядок): вычет по НПО применяется к
              //               договорам с 2025 года, поэтому пп. 1 в форме
              //               за 2024 нет;
              //   2025+     — все атрибуты необязательные, добавлены пп. 1,
              //               пп. 5 и разбивка «агент / упрощёнка / декларация».
              (sv.eligible > 0 || sv.byAgent > 0) &&
                year >= 2024 &&
                (year >= 2025
                  ? el("РасчВычСбер", {
                      ...(sv.npo > 0 ? { "ВычСбер1.1.219.2": kop2(sv.npo) } : {}),
                      ...(sv.pds > 0 ? { "ВычСбер2.1.219.2": kop2(sv.pds) } : {}),
                      ...(sv.iis3 > 0 ? { "ВычСбер3.1.219.2": kop2(sv.iis3) } : {}),
                      ...(sv.life10 > 0 ? { "ВычСбер5.1.219.2": kop2(sv.life10) } : {}),
                      ...(sv.byAgent > 0 ? { ВычНалПер: kop2(sv.byAgent) } : {}),
                      ...(sv.simplified > 0 ? { ВычУпрОбщ: kop2(sv.simplified) } : {}),
                      ВычДекл: kop2(sv.declared),
                    })
                  : el("РасчВычСбер", {
                      "ВычСбер2.1.219.2": kop2(sv.pds),
                      "ВычСбер3.1.219.2": kop2(sv.iis3),
                      ВычСберУпр: kop2(sv.simplified),
                    }))
            ),
          // --- Приложение 6: имущественный вычет по доходам от продажи ---
          // ОбщИмущВыч (стр. 160) — итоговая сумма вычета. Дочерний элемент по
          // типу имущества: жилая недвижимость и земля (пункт 1) — ВычДохНедвЖил
          // (ВычПродИмущ — вычет 1 млн ₽ / РасхПриобИмущ — расходы); авто и иное
          // движимое (пункт 3) — ВычПродИмущИн (ВычДохПродИмущ — вычет 250 тыс ₽
          // / РасхПриобрИмущ — расходы). Имена атрибутов различаются (сверено с
          // XSD: тип СвСумПр6 у иного имущества, inline-атрибуты у жилья).
          // Пунктов в Приложении 6 три — жильё с землёй, иное недвижимое и
          // иное (движимое) имущество, — и суммы в них ГОДОВЫЕ, на все
          // проданные объекты класса сразу. Лимиты у пунктов независимы.
          // Внутри пункта фиксированный вычет и расходы на покупку живут в
          // разных атрибутах, поэтому «одну машину по вычету, другую по
          // расходам» форма выражает без потерь.
          sale &&
            el(
              "ИмущНалВычПр",
              { ОбщИмущВыч: kop2(sale.deduction) },
              sale.ded.home.has &&
                el("ВычДохНедвЖил", {
                  ВычПродИмущ:
                    sale.ded.home.standard > 0 ? kop2(sale.ded.home.standard) : undefined,
                  РасхПриобИмущ:
                    sale.ded.home.expenses > 0 ? kop2(sale.ded.home.expenses) : undefined,
                }),
              // Иное недвижимое (гараж, машиноместо, апартаменты) — свой пункт
              // со своим лимитом 250 000 ₽, не общим с движимым имуществом.
              sale.ded.realtyOther.has &&
                el("ВычПродНедвИн", {
                  ВычДохПродИмущ:
                    sale.ded.realtyOther.standard > 0 ? kop2(sale.ded.realtyOther.standard) : undefined,
                  РасхПриобрИмущ:
                    sale.ded.realtyOther.expenses > 0 ? kop2(sale.ded.realtyOther.expenses) : undefined,
                }),
              sale.ded.movable.has &&
                el("ВычПродИмущИн", {
                  ВычДохПродИмущ:
                    sale.ded.movable.standard > 0 ? kop2(sale.ded.movable.standard) : undefined,
                  РасхПриобрИмущ:
                    sale.ded.movable.expenses > 0 ? kop2(sale.ded.movable.expenses) : undefined,
                })
            ),
          // --- Приложение 7: имущественный вычет по приобретению жилья ---
          pr &&
            el(
              "ИмущНалВычНов",
              {},
              el(
                "РасчИмущВыч",
                {
                  // ВычНАУпр — это вычет, УЖЕ ПРЕДОСТАВЛЕННЫЙ В УПРОЩЁННОМ
                  // ПОРЯДКЕ (строка 121 бланка), формулировка дословно из
                  // схемы ФНС. Сюда по ошибке писалась вся заявляемая сумма:
                  // получалось, что человек одновременно просит вычет и
                  // сообщает, что уже его получил. Схема атрибут не требует
                  // (use="optional"), в анкете такого поля нет — не пишем.
                  // Заявляемое по декларации живёт в РасхНовВычНД (строка 150).
                  РасхНовВычНД: ap.property > 0 ? kop2(ap.property) : undefined,
                  ПроцВычНД: ap.interest > 0 ? kop2(ap.interest) : undefined,
                  ОстИВБезПроц: kop2(calc.carryover.property),
                  ОстИВУплПроц: kop2(calc.carryover.interest),
                },
                el(
                  "СвОбъектРасх",
                  {
                    КодНаимОб: pr.codes.object,
                    ПризнакНП: pr.codes.sign,
                    // Дата регистрации права появилась в СвОбъектРасх с 2024 года.
                    ДатаРегОб: !isOld && pr.dateReg ? dateRu(pr.dateReg) : undefined,
                    СумРасхФакт: pr.cost > 0 ? kop2(Math.min(pr.cost, 2_000_000)) : undefined,
                    СумФактУплПроц: pr.interestPaid > 0 ? kop2(pr.interestPaid) : undefined,
                  },
                  el("СведОбъект", {
                    // До 2024 объект задаётся кодом номера + номером.
                    КодНомерОб: isOld ? (pr.cadastral ? "1" : "4") : undefined,
                    НомерОб: pr.cadastral || "0",
                    // Способ приобретения — только для жилых домов (строка 030
                    // формы); атрибут опционален в схемах всех лет.
                    СпособПриобр: pr.codes.build || undefined,
                  })
                )
              )
            ),
          // --- Расчёт к Приложению 1: сверка дохода с кадастровой стоимостью ---
          // Только недвижимость (ст. 214.10 НК). Элемент ДохПродОНИ — прямой
          // потомок НДФЛ3, по порядку XSD идёт после ИмущНалВычНов (Прил. 7) и
          // ДохОперЦБ. До 2025 атрибуты лежат прямо на ДохПродОНИ; с 2025 — на
          // вложенном ДохОНИ с признаком ВидДох ("1" — доход определён с учётом
          // кадастра). Кадастровую стоимость требуем на шаге «Продажа», поэтому
          // все обязательные поля (в форме до 2025 обязательны все пять) есть.
          // --- Расчёт к Приложению 1: сверка дохода с кадастровой стоимостью ---
          // Только недвижимость (ст. 214.10 НК), по блоку на каждый объект.
          // Элемент ДохПродОНИ — прямой потомок НДФЛ3, по порядку XSD идёт
          // после ИмущНалВычНов (Прил. 7) и ДохОперЦБ. До 2025 атрибуты лежат
          // прямо на ДохПродОНИ и сам он повторяется; с 2025 — один ДохПродОНИ
          // с вложенными ДохОНИ (признак ВидДох «1» — доход определён с учётом
          // кадастра). Кадастровую стоимость требуем на шаге «Продажа»,
          // поэтому все обязательные поля заполнены.
          ...(() => {
            const realty = sale ? sale.items.filter((o) => o.kind === "realty") : [];
            if (!realty.length) return [];
            const cad = (o) => ({
              НомКадОтчуждОНИ: o.cadastralNumber || "0",
              КадСтоимГодРег: kop2(o.cadastral),
              ДохПродЦенаДог: kop2(o.price),
              КадСтоимКоэф: kop2(o.cadastralTaxable),
              ДохПродНалОбл: kop2(o.taxable),
            });
            return is2025
              ? [el("ДохПродОНИ", {}, ...realty.map((o) => el("ДохОНИ", { ВидДох: "1", ...cad(o) })))]
              : realty.map((o) => el("ДохПродОНИ", cad(o)));
          })(),
          // --- Расчёт к Приложению 5 -------------------------------------------
          // Лист-расчёт под строки 160 (взносы по договору страхования жизни) и
          // 210 (взносы на ИИС) Приложения 5. По Порядку заполнения (п. 78, 106)
          // эти строки берутся именно отсюда, поэтому без листа декларация
          // неполна. Реквизиты организации (ИНН, КПП, наименование) обязательны
          // по схеме — их спрашиваем на шаге «Расходы».
          //
          // Форма элемента менялась: до 2024 года блок ИИС ВЛОЖЕН в
          // РасчПенсВзнос, который требует ОбщВзносВыч, а признаков ПрВыч и
          // ПрОснВыч ещё нет. С 2024 года блок ИИС — самостоятельный, признаки
          // появились. Обе формы проверены по официальным XSD.
          ...(() => {
            const ins = calc.lines.insurance > 0 && ct.insurance?.insurerInn ? ct.insurance : null;
            const iisSum = ap.iis > 0 ? ap.iis : sv.iis3;
            const iis = iisSum > 0 && ct.iis?.brokerInn ? ct.iis : null;
            const legacy = model.year < 2024;
            // Блоки 1.1 листа-расчёта. Каждый договор — свой блок; в XML они
            // складываются в РасчПСВВыч (maxOccurs="unbounded"). Код вида
            // договора берётся из подсказки на самом бланке:
            //   1 — негосударственное пенсионное обеспечение,
            //   3 — страхование жизни по пп. 4 п. 1 ст. 219 (социальный вычет),
            //   4 — договор долгосрочных сбережений,
            //   5 — страхование жизни по пп. 5 п. 1 ст. 219.2 (код добавлен
            //       приказом ЕД-1-11/333@, в схеме до 2025 года его нет).
            const SAVE_CODE = { npo: "1", pds: "4", life10: "5" };
            const svContracts = (sv.eligible > 0 ? ct.savings || [] : [])
              .filter((c) => SAVE_CODE[c.kind] && Number(c.amount) > 0 && digits(c.inn))
              // Подпункты 1 и 5 применяются к договорам с 2025 года: за 2024
              // и код «5», и вычет по НПО схема не примет.
              .filter((c) => model.year >= 2025 || c.kind === "pds");
            const blocks = [
              ...(ins
                ? [{
                    amount: calc.lines.insurance,
                    code: "3",
                    date: ins.contractDate,
                    number: ins.contractNumber,
                    name: ins.insurerName,
                    inn: ins.insurerInn,
                    kpp: ins.insurerKpp,
                  }]
                : []),
              ...svContracts.map((c) => ({
                amount: Number(c.amount),
                code: SAVE_CODE[c.kind],
                date: c.date,
                number: c.number,
                name: c.name,
                inn: c.inn,
                kpp: c.kpp,
              })),
            ];
            if (!blocks.length && !iis) return [];
            const psvList = blocks.map((b) =>
              el(
                "РасчПСВВыч",
                { СумВзносУпл: kop2(b.amount), ...(legacy ? {} : { ПрВыч: "0" }) },
                el(
                  "СведДогНПО",
                  {
                    ВидДоговор: b.code,
                    ДатаДогНПО: dateRu(b.date),
                    НомДогНПО: b.number,
                  },
                  el("СведИст", {
                    Наим: b.name,
                    ИННЮЛ: digits(b.inn),
                    КПП: digits(b.kpp),
                  })
                )
              )
            );
            const inv =
              iis &&
              el("РасчСумИнвВыч", {
                // 1 — вычет по статье 219.1 НК (взносы на ИИС).
                ...(legacy ? {} : { ПрОснВыч: ct.iis?.newAccount ? "2" : "1" }),
                ИННЮЛ: digits(iis.brokerInn),
                КПП: digits(iis.brokerKpp),
                НаимУч: iis.brokerName,
                ДатаДог: dateRu(iis.contractDate),
                НомДог: iis.contractNumber,
                ДатаОткр: dateRu(iis.openDate),
                ОбщСумВыч: kop2(iisSum),
                ПрВыч: "0",
              });
            const total = blocks.reduce((a, b) => a + b.amount, 0);
            return [
              legacy
                ? el(
                    "ВычСоцИнв219",
                    {},
                    el("РасчПенсВзнос", { ОбщВзносВыч: kop2(total) }, ...psvList, inv)
                  )
                : el(
                    "ВычСоцИнв219",
                    {},
                    psvList.length && el("РасчПенсВзнос", {}, ...psvList),
                    inv
                  ),
            ];
          })()
        )
      )
    );

  return {
    filename: `${fileId}.xml`,
    bytes: encodeCp1251(xml),
    verified: Boolean(rules.xmlVerified),
  };
}
