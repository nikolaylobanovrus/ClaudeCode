function wrap(text, font, size, maxWidth) {
  const words = String(text).split(/\s+/);
  const lines = [];
  let line = "";
  for (const w of words) {
    const probe = line ? line + " " + w : w;
    if (font.widthOfTextAtSize(probe, size) <= maxWidth) line = probe;
    else {
      if (line) lines.push(line);
      line = w;
    }
  }
  if (line) lines.push(line);
  return lines;
}

export async function buildInstructionPdf({ year, types = [] }) {
  const ctx = await createDoc();
  let page = ctx.doc.addPage([A4.w, A4.h]);
  let y = A4.h - M;

  const newPageIfNeeded = (need) => {
    if (y - need < M) {
      page = ctx.doc.addPage([A4.w, A4.h]);
      y = A4.h - M;
    }
  };
  const text = (t, { size = 10, bold = false, color = INK, indent = 0, gap = 4 } = {}) => {
    const font = bold ? ctx.fontBold : ctx.font;
    for (const line of wrap(t, font, size, WIDTH - indent)) {
      newPageIfNeeded(size + gap);
      page.drawText(line, { x: M + indent, y: y - size, size, font, color });
      y -= size + gap;
    }
  };
  const h1 = (t) => {
    newPageIfNeeded(30);
    y -= 6;
    text(t, { size: 16, bold: true, color: BLUE, gap: 8 });
  };
  const h2 = (t) => {
    newPageIfNeeded(26);
    y -= 8;
    text(t, { size: 12.5, bold: true, gap: 6 });
  };
  const li = (t) => text("•  " + t, { indent: mm(3), gap: 3.5 });
  const step = (n, t) => text(`${n}. ${t}`, { indent: mm(3), gap: 4.5 });
  const gap = (v = 6) => {
    y -= v;
  };

  // ===== Титул =====
  text("Налог-сервис · налог-сервис.рф", { size: 9, color: MUTED, gap: 10 });
  h1(`Как подать декларацию 3-НДФЛ за ${year} год`);
  text(
    "В вашем комплекте три файла: декларация (PDF), файл для Личного кабинета ФНС (XML) и заявление на возврат. Подать декларацию можно любым из трёх способов ниже — выберите удобный.",
    { color: MUTED, gap: 5 }
  );

  // ===== Способ 1 =====
  h2("Способ 1. Через Личный кабинет ФНС (рекомендуем — без бумаги и очередей)");
  step(1, "Зайдите на lkfl2.nalog.ru и войдите через Госуслуги (кнопка «Войти через ЕСИА»).");
  step(2, "Один раз получите электронную подпись: Настройки профиля → Электронная подпись → «Ключ в защищённой системе ФНС». Придумайте пароль подписи. Выпуск занимает от 15 минут до суток — дождитесь статуса «Сертификат выпущен».");
  step(3, "Меню «Декларации» → «Подать декларацию» → «Подать декларацию 3-НДФЛ» → «Загрузить готовую декларацию».");
  step(4, `Выберите год ${year} и приложите XML-файл из комплекта. Если сайт не принял файл — заполните декларацию прямо в кабинете, перенося цифры из нашего PDF (10–15 минут).`);
  step(5, "Прикрепите сканы или фото подтверждающих документов (список ниже).");
  step(6, "Введите пароль электронной подписи и нажмите «Подтвердить и отправить».");
  step(7, "Камеральная проверка идёт до 3 месяцев. Статус виден в кабинете. Возврат придёт на счёт из заявления; если через месяц после проверки денег нет — в кабинете нажмите «Распорядиться переплатой».");

  // ===== Способ 2 =====
  h2("Способ 2. Почтой");
  step(1, "Распечатайте декларацию (PDF) и заявление на возврат. Подпишите декларацию внизу каждого листа и поставьте дату.");
  step(2, "Приложите КОПИИ подтверждающих документов (оригиналы храните у себя).");
  step(3, "Узнайте адрес своей инспекции по прописке: service.nalog.ru/addrno.do.");
  step(4, "Отправьте ЦЕННЫМ письмом с ОПИСЬЮ ВЛОЖЕНИЯ (форма 107 — бланк дадут на почте): перечислите в описи каждый документ. Один экземпляр описи со штампом почты оставьте себе.");
  step(5, "Датой подачи считается дата отправки письма. Квитанцию и опись храните до конца проверки.");

  // ===== Способ 3 =====
  h2("Способ 3. Лично в инспекцию или МФЦ");
  step(1, "Распечатайте декларацию в ДВУХ экземплярах и подпишите каждый лист обоих.");
  step(2, "Возьмите паспорт, подтверждающие документы (оригиналы и копии) и заявление на возврат.");
  step(3, "В свою инспекцию — по записи через order.nalog.ru или с талоном на месте. В МФЦ — заранее уточните, что центр принимает декларации 3-НДФЛ.");
  step(4, "Один экземпляр отдадите инспектору, на втором поставят отметку о приёме — он ваш, храните его.");

  // ===== Подтверждающие документы =====
  const chosen = types.filter((t) => PROOF_DOCS[t]);
  h2("Подтверждающие документы к вашей декларации");
  if (chosen.length) {
    for (const t of chosen) {
      text(PROOF_TITLES[t] + ":", { bold: true, gap: 3 });
      for (const d of PROOF_DOCS[t]) li(d);
      gap(3);
    }
  } else {
    text("Приложите документы, подтверждающие доходы и заявленные вычеты.", { gap: 4 });
  }
  gap(2);
  text(
    "Справку о доходах (2-НДФЛ) прикладывать не обязательно — налоговая видит её от работодателя, но приложить не будет ошибкой.",
    { size: 9, color: MUTED, gap: 4 }
  );

  gap(8);
  text(
    "Вопросы? Мы на связи: +7 (920) 837-91-93, страница инструкции — налог-сервис.рф/#/deklaraciya/instrukciya",
    { size: 9, color: MUTED }
  );

  return ctx.doc.save();
}
