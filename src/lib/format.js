// Общие форматтеры мастера декларации: одна точка правды для денег и цифр.

// «156 000 ₽» — округляем до рубля (копейки в интерфейсе не показываем).
export const fmtRub = (n) =>
  Math.round(Number(n) || 0).toLocaleString("ru-RU") + " ₽";

// Оставить только цифры (ИНН, счёт, ОКТМО и т.п.) — в т.ч. вычищает
// пробелы и невидимые символы из значений, вставленных из банковских
// приложений.
export const digits = (s) => String(s || "").replace(/\D/g, "");
