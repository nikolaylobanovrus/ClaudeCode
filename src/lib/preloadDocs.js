// Предзагрузка движка документов.
//
// Зачем. Комплект собирается в браузере: pdf-lib, fontkit, сами бланки — около
// 2,5 МБ, и всё это тянется динамическими import() только в момент, когда
// человек уже заплатил и ждёт документы (StepDocuments.jsx). На медленном
// мобильном интернете это десятки секунд ожидания у того, кто уже отдал деньги.
//
// Что делаем. Начинаем качать заранее, в два этапа: код — на шаге «Проверка»,
// пока человек читает расчёт и ещё не нажал «Оплатить»; тяжёлые двоичные
// файлы (бланк ФНС, шрифты) — на шаге оплаты. К моменту, когда они
// понадобятся, они уже в памяти вкладки: повторный import() отдаёт модуль из
// кеша мгновенно, а fetch бланка — из того же кэша обещаний в blankPdf.js.
//
// Пути указаны ТЕМИ ЖЕ модулями, что и в StepDocuments: сборщик сводит их к
// одним и тем же кускам бандла, поэтому второй import() ничего не докачивает.
//
// Ошибки намеренно глотаем: это ускорение, а не функциональность. Нет сети —
// человек просто подождёт на шаге «Документы», как и раньше. Флаг при неудаче
// сбрасываем, чтобы попытка повторилась, когда связь вернётся.
let started = false;
let modules = null;

function engine() {
  modules ||= Promise.all([
    import("./ndfl/model.js"),
    import("./ndfl/pdf3ndfl.js"),
    import("./ndfl/zayavlenie.js"),
    import("./ndfl/xml3ndfl.js"),
    import("./ndfl/instrukciya.js"),
  ]).catch((e) => {
    modules = null;
    started = false;
    throw e;
  });
  return modules;
}

// Первый этап — код: шаг «Проверка», до оплаты.
export function preloadDocEngine() {
  if (started) return;
  started = true;
  engine().catch(() => {});
}

// Второй этап — двоичные файлы: бланк ФНС нужного года (410–767 КБ) и
// шрифты (ещё ~1,1 МБ). Их отложили до шага оплаты по двум причинам:
//
//  1. Трафик. На «Проверку» заходят и те, кто не заплатит; тянуть им лишние
//     полтора мегабайта с мобильного интернета незачем.
//  2. ЮKassa. Боевая оплата уводит со страницы, и память вкладки теряется.
//     Но файлы в /assets отдаются с immutable на год, поэтому прогретые
//     байты лежат в кеше браузера и переживают возврат с оплаты —
//     а на возврате шаг оплаты смонтируется снова и догреет остальное,
//     пока поллинг ждёт вебхук.
//
// year — год декларации: бланки у годов разные, греть все четыре смысла нет.
let warmedYear = null;
export function preloadDocAssets(year) {
  if (!year || warmedYear === year) return;
  warmedYear = year;
  engine()
    .then(([, pdf3ndfl]) =>
      Promise.all([pdf3ndfl.preloadBlank(year), preloadZayavlenieFonts()])
    )
    .catch(() => {
      warmedYear = null;
    });
}

// Шрифты заявления и инструкции (они печатаются не на бланке ФНС, а с нуля).
function preloadZayavlenieFonts() {
  return import("./ndfl/pdfPage.js").then((m) => m.preloadFonts());
}
